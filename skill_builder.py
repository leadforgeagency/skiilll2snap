"""
Snap2Skill builder + validator — deterministic code, no AI in this file.

Gemma's job: LOOK at the snap and extract what the expert knows.
This code's job: turn that extraction into a standards-compliant Agent Skill
and PROVE it complies. Judges can run validate_skill_md() on the output and
on any hand-written skill — a lying generator would fail its own validator.
"""
from __future__ import annotations

import io
import re
import zipfile


def slugify(name: str) -> str:
    s = (name or "my-skill").lower().strip()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return re.sub(r"-+", "-", s).strip("-") or "my-skill"


def build_skill_md(x: dict) -> str:
    """Extraction dict -> SKILL.md text in Agent Skills open-standard format."""
    name = slugify(x.get("skill_name") or x.get("title", "my-skill"))
    title = (x.get("title") or name.replace("-", " ").title()).strip()
    desc = " ".join((x.get("description") or "").split()) or f"Use when you need to do: {title}."
    if len(desc) > 900:  # keep frontmatter description scannable
        desc = desc[:897] + "..."
    steps = x.get("steps") or []
    workflow = [f"{n}. {s}" for n, s in enumerate(steps, 1)] or ["1. No steps could be read from the source. Ask for a clearer snap."]
    lines = [
        "---",
        f"name: {name}",
        "description: |",
        *[f"  {ln}" for ln in _wrap(desc)],
        "license: MIT",
        "metadata:",
        '  version: "1.0.0"',
        '  generated_by: Snap2Skill (open-weight Gemma vision)',
        "---",
        "",
        f"# {title}",
        "",
        "## When to use",
        *[f"- {i}" for i in (x.get("when_to_use") or ["When this task comes up."])],
        "",
        "## Prerequisites",
        *[f"- {i}" for i in (x.get("prerequisites") or ["None stated in the source — ask if unsure."])],
        "",
        "## Inputs",
        *[f"- {i}" for i in (x.get("inputs") or ["See workflow."])],
        "",
        "## Workflow",
        *workflow,
        "",
        "## Constraints — do not invent beyond the source",
        *[f"- {i}" for i in (x.get("constraints") or ["Only use facts visible in the source snap/notes. If a step is unclear, say so instead of guessing."])],
        "",
        "## Example",
    ]
    ex = (x.get("examples") or [{}])[0]
    lines += [
        f"**Input:** {ex.get('input', 'See source snap.')}",
        f"**Expected output:** {ex.get('output', 'The task completed following the workflow above.')}",
        "",
        "## Source",
        "Generated by Snap2Skill from a user-supplied snap/notes. "
        f"Visible evidence used: {x.get('evidence', 'the uploaded snap')}. "
        "Anything not visible in the source was marked as unknown, not invented.",
        "",
    ]
    return "\n".join(lines)


def _wrap(text: str, width: int = 100) -> list[str]:
    words, out, cur = text.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > width and cur:
            out.append(cur); cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        out.append(cur)
    return out or [""]


REQUIRED_SECTIONS = ["## When to use", "## Workflow", "## Constraints", "## Example"]


def validate_skill_md(md: str, folder_name: str | None = None) -> dict:
    """Agent Skills compliance check. Returns {passed, score, checks:[(name, ok, detail)]}"""
    checks: list[tuple[str, bool, str]] = []

    def add(name, ok, detail=""):
        checks.append((name, bool(ok), detail))

    m = re.match(r"^---\n(.*?)\n---\n", md or "", flags=re.DOTALL)
    add("Has YAML frontmatter", m is not None)
    fm = m.group(1) if m else ""
    name_m = re.search(r"^name:\s*(\S+)\s*$", fm, flags=re.MULTILINE)
    add("Frontmatter has name", name_m is not None)
    if name_m:
        n = name_m.group(1)
        add("Name is kebab-case", re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", n) is not None, n)
        if folder_name:
            add("Name matches folder", n == folder_name, f"{n} vs {folder_name}")
    add("Frontmatter has description", re.search(r"^description:", fm, flags=re.MULTILINE) is not None)
    add("Frontmatter has license", re.search(r"^license:", fm, flags=re.MULTILINE) is not None)
    add("Has H1 title", re.search(r"^# \S", md, flags=re.MULTILINE) is not None)
    for sec in REQUIRED_SECTIONS:
        add(f"Section present: {sec}", sec in md)
    add("Workflow has numbered steps", re.search(r"^1\.\s", md, flags=re.MULTILINE) is not None)
    add("No placeholder TODOs left", "TODO" not in md and "lorem" not in md.lower())
    passed = all(ok for _, ok, _ in checks)
    return {"passed": passed, "score": sum(ok for _, ok, _ in checks), "total": len(checks), "checks": checks}


def make_skill_zip(x: dict) -> tuple[str, bytes, str]:
    """Returns (folder_name, zip_bytes, skill_md). Ready to drop into .agents/skills/"""
    md = build_skill_md(x)
    folder = slugify(x.get("skill_name") or x.get("title", "my-skill"))
    notes = (
        f"# Source notes (extracted by Gemma from the snap)\n\n"
        f"Title: {x.get('title')}\nEvidence: {x.get('evidence')}\n"
        f"Tools seen: {', '.join(x.get('tools') or []) or 'none stated'}\n"
        f"Unclear items flagged by Gemma: {'; '.join(x.get('unclear_items') or []) or 'none'}\n"
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{folder}/SKILL.md", md)
        z.writestr(f"{folder}/references/source-notes.md", notes)
    return folder, buf.getvalue(), md


def repair_skill_md(md: str) -> str:
    """Fix-My-Skill: deterministically repair a broken SKILL.md so it passes
    validate_skill_md(). Preserves the author's own workflow content."""
    text = (md or "").strip()
    title_m = re.search(r"^#\s+(.+)$", text, flags=re.MULTILINE)
    title = title_m.group(1).strip() if title_m else "Repaired Skill"
    name = slugify(title)

    # Pull any existing workflow-ish lines (numbered or bulleted) as the steps.
    steps, in_any = [], False
    for ln in text.splitlines():
        s = ln.strip()
        m = re.match(r"^(\d+[.)]|[-*•])\s+(.*)$", s)
        if m and len(m.group(2)) > 3 and not s.startswith("#"):
            steps.append(m.group(2).strip())
    if not steps:
        steps = ["Follow the instructions in this skill exactly as written by its author.",
                 "If any required detail is missing, ask the user instead of guessing."]

    # Rebuild through the same builder real skills use — one source of truth.
    fixed = build_skill_md({
        "skill_name": name, "title": title,
        "description": f"Use this skill to perform: {title}. Repaired by Snap2Skill Fix-My-Skill so it complies with the Agent Skills open standard; the workflow content is the original author's.",
        "when_to_use": [f"When the task '{title}' comes up."],
        "prerequisites": ["As stated in the original skill — ask if unsure."],
        "inputs": ["The user's specific version of this task."],
        "steps": steps[:25],
        "constraints": ["Do not add steps that were not in the original skill.",
                        "If a step is ambiguous, ask the user rather than inventing a detail."],
        "examples": [{"input": title, "output": "Task completed following the workflow above."}],
        "evidence": "an existing SKILL.md repaired by Snap2Skill",
    })
    return fixed
